// Fetches the latest uploads of the Chemistry Guru YouTube channel and writes
// src/app/data/videos.ts, which the site pre-renders into the "Latest videos" section.
//
// Runs in GitHub Actions before every build (see .github/workflows/deploy.yml) with the
// YOUTUBE_API_KEY repository secret. Without a key it leaves the existing list unchanged.
//
// Local run:  $env:YOUTUBE_API_KEY = "..."; node scripts/fetch-videos.mjs

import { writeFileSync, readFileSync } from 'node:fs';

const KEY = process.env.YOUTUBE_API_KEY;
const UPLOADS_PLAYLIST = 'UU0uOhUYOAEewdUF0nFeuzhA'; // channel UC0uOhUYOAEewdUF0nFeuzhA
const COUNT = 6;
const OUT = new URL('../src/app/data/videos.ts', import.meta.url);
const API = 'https://www.googleapis.com/youtube/v3';

if (!KEY) {
  console.warn('YOUTUBE_API_KEY is not set – keeping the existing video list.');
  process.exit(0);
}

async function api(path, params) {
  const url = `${API}/${path}?${new URLSearchParams({ ...params, key: KEY })}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`YouTube API ${path} failed: ${res.status} ${await res.text()}`);
  return res.json();
}

/** ISO 8601 duration (PT1H2M3S) to seconds. */
function seconds(iso) {
  const [, h = 0, m = 0, s = 0] = iso.match(/PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?/) ?? [];
  return +h * 3600 + +m * 60 + +s;
}

/** Shorts are at most 3 minutes; for short clips ask YouTube whether /shorts/<id> exists. */
async function isShort(id, duration) {
  if (duration > 180) return false;
  try {
    const res = await fetch(`https://www.youtube.com/shorts/${id}`, { method: 'HEAD', redirect: 'manual' });
    return res.status === 200;
  } catch {
    return true; // unsure – leave it out
  }
}

try {
  const list = await api('playlistItems', { part: 'contentDetails', playlistId: UPLOADS_PLAYLIST, maxResults: '50' });
  const ids = list.items.map(i => i.contentDetails.videoId);
  const details = await api('videos', { part: 'snippet,contentDetails,status', id: ids.join(',') });

  const videos = [];
  for (const v of details.items) {
    if (v.status.privacyStatus !== 'public' || v.snippet.liveBroadcastContent !== 'none') continue;
    if (await isShort(v.id, seconds(v.contentDetails.duration))) continue;
    videos.push({ id: v.id, title: v.snippet.title.trim(), published: v.snippet.publishedAt.slice(0, 10) });
  }
  videos.sort((a, b) => b.published.localeCompare(a.published));
  const latest = videos.slice(0, COUNT);

  if (!latest.length) {
    console.warn('No public videos found – keeping the existing video list.');
    process.exit(0);
  }

  const file = `// Generated by scripts/fetch-videos.mjs – do not edit by hand.
export interface Video {
  id: string;
  title: string;
  /** Upload date, YYYY-MM-DD. */
  published: string;
}

export const LATEST_VIDEOS: Video[] = ${JSON.stringify(latest, null, 2)};
`;
  const current = readFileSync(OUT, 'utf8');
  if (current !== file) writeFileSync(OUT, file);
  console.log(`Latest videos (${latest.length}):\n${latest.map(v => `  ${v.published}  ${v.title}`).join('\n')}`);
} catch (err) {
  // Never break the site build because YouTube is unreachable.
  console.warn(`Could not refresh videos – keeping the existing list.\n${err.message}`);
}
